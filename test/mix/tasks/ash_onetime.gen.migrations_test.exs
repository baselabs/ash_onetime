defmodule Mix.Tasks.AshOnetime.Gen.MigrationsTest do
  use ExUnit.Case, async: false

  alias AshOnetime.Test.Repo
  alias Ecto.Adapters.SQL
  alias Ecto.Adapters.SQL.Sandbox

  alias AshOnetime.Resource.ContextBoundary
  alias Mix.Tasks.AshOnetime.Gen.LogicalPartitions
  alias Mix.Tasks.AshOnetime.Gen.Migrations, as: GenerateMigrations

  setup do
    temporary =
      Path.join(System.tmp_dir!(), "ash_onetime_generator_#{System.unique_integer([:positive])}")

    on_exit(fn -> File.rm_rf!(temporary) end)
    {:ok, temporary: temporary}
  end

  test "generates the reversible unpartitioned migration from the shipped template", %{
    temporary: temporary
  } do
    path = run_generator(temporary, [])
    source = File.read!(path)

    assert source =~ "id uuid PRIMARY KEY"
    refute source =~ "PARTITION BY HASH (operation_hash)"

    assert source =~
             ~S|encoded_response bytea NOT NULL CHECK (octet_length(encoded_response) <= #{@payload_ceiling})|

    assert source =~ "ash_onetime_response_payloads_default"
    assert source =~ "def down do"
  end

  test "generates native hash claim partitions only with a valid paired option", %{
    temporary: temporary
  } do
    path = run_generator(temporary, ["--claims", "hash", "--claim-partitions", "4"])
    source = File.read!(path)

    assert source =~ "PRIMARY KEY (operation_hash, logical_partition, id)"
    assert source =~ "PARTITION BY HASH (operation_hash)"
    assert source =~ "count = 4"
    assert source =~ ~S|FOR VALUES WITH (MODULUS #{count}, REMAINDER #{remainder})|

    second_path = Path.join(temporary, "missing-pair")

    assert_raise Mix.Error, ~r/requires --claim-partitions/, fn ->
      run_generator(second_path, ["--claims", "hash"])
    end

    assert File.ls!(second_path) == []
  end

  test "refuses duplicate install generation", %{temporary: temporary} do
    _path = run_generator(temporary, [])

    assert_raise Mix.Error, ~r/already exists/, fn ->
      run_generator(temporary, [])
    end
  end

  test "generates a fact-table migration only with --fact-tables", %{temporary: temporary} do
    plain = Path.join(temporary, "plain")
    path = run_generator(plain, [])
    assert Path.wildcard(Path.join(plain, "*_ash_onetime_context_boundary_facts.exs")) == []
    assert File.exists?(path)

    facts_dir = Path.join(temporary, "facts")

    facts_path =
      run_generator(
        facts_dir,
        ["--fact-tables", "ledger_facts,payment_facts", "--timestamp", "20261108000000"]
      )

    assert Path.basename(facts_path) == "20261108000000_ash_onetime_context_boundary_facts.exs"

    source = File.read!(facts_path)
    # The table names are emitted as a literal list and interpolated at
    # migration-run time through the same q/1 helper the install migration uses.
    assert source =~ ~S|for table <- ["ledger_facts", "payment_facts"] do|
    assert source =~ ~S|CREATE TABLE #{q(table)} (|
    assert source =~ "seq bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
    assert source =~ "tags text[] NOT NULL"
    assert source =~ ~S|USING gin (tags)|
    assert source =~ "ash_onetime_fact_append_only"
    assert source =~ "def down do"

    assert source =~
             GenerateMigrations.render_fact_tables(Repo,
               fact_tables: ["ledger_facts", "payment_facts"]
             )
  end

  # CREATE INDEX and CREATE TRIGGER names must stay unqualified: both land in
  # the table's schema automatically, and a qualified name is a syntax error
  # under a tenant prefix (the class the livebook gate caught).
  test "the fact-table migration runs up and down under a schema prefix", %{temporary: temporary} do
    File.mkdir_p!(temporary)
    source = GenerateMigrations.render_fact_tables(Repo, fact_tables: ["prefix_facts"])
    path = Path.join(temporary, "20261108000002_ash_onetime_context_boundary_facts.exs")
    File.write!(path, source)
    [{module, _}] = Code.compile_file(path)
    version = 2_026_110_800_002
    schema = "ash_onetime_facts_#{System.unique_integer([:positive])}"

    Sandbox.mode(Repo, :auto)

    try do
      SQL.query!(Repo, ~s{CREATE SCHEMA "#{schema}"}, [])

      for round <- 1..2 do
        :ok = Ecto.Migrator.up(Repo, version, module, prefix: schema, log: false)
        :ok = Ecto.Migrator.down(Repo, version, module, prefix: schema, log: false)
      end

      :ok = Ecto.Migrator.up(Repo, version, module, prefix: schema, log: false)
    after
      SQL.query!(Repo, ~s{DROP SCHEMA IF EXISTS "#{schema}" CASCADE}, [])
      Sandbox.mode(Repo, :manual)
    end
  end

  test "renders the RLS prune migration only with --rls-prune --app-role", %{temporary: temporary} do
    plain = Path.join(temporary, "plain")
    run_generator(plain, [])
    assert Path.wildcard(Path.join(plain, "*_ash_onetime_rls_prune.exs")) == []

    dir = Path.join(temporary, "rls")
    Mix.Task.reenable("ash_onetime.gen.migrations")

    path =
      GenerateMigrations.run([
        "--repo",
        inspect(Repo),
        "--migrations-path",
        dir,
        "--rls-prune",
        "--app-role",
        "my_app",
        "--timestamp",
        "20261109000000"
      ])

    assert Path.basename(path) == "20261109000000_ash_onetime_rls_prune.exs"

    source = File.read!(path)

    for marker <- [
          "CREATE ROLE %I NOLOGIN",
          "GRANT %I TO %I WITH INHERIT FALSE, SET TRUE",
          "SECURITY DEFINER",
          "ash_onetime_partition_empty",
          "must not be the application role",
          "SET, USAGE, or ADMIN",
          "ash_onetime_prune_select",
          "CREATE POLICY",
          "FORCE ROW LEVEL SECURITY"
        ] do
      assert source =~ marker
    end

    assert source =~ GenerateMigrations.render_rls_prune(Repo, app_role: "my_app")

    assert_raise Mix.Error, ~r/requires --app-role/, fn ->
      Mix.Task.reenable("ash_onetime.gen.migrations")

      GenerateMigrations.run([
        "--repo",
        inspect(Repo),
        "--migrations-path",
        dir,
        "--rls-prune"
      ])
    end

    assert_raise Mix.Error, ~r/--app-role is only valid/, fn ->
      Mix.Task.reenable("ash_onetime.gen.migrations")

      GenerateMigrations.run([
        "--repo",
        inspect(Repo),
        "--migrations-path",
        dir,
        "--app-role",
        "my_app"
      ])
    end

    assert_raise Mix.Error, ~r/lowercase SQL identifier/, fn ->
      Mix.Task.reenable("ash_onetime.gen.migrations")

      GenerateMigrations.run([
        "--repo",
        inspect(Repo),
        "--migrations-path",
        dir,
        "--rls-prune",
        "--app-role",
        "My-App"
      ])
    end
  end

  test "refuses reserved and malformed fact-table names", %{temporary: temporary} do
    for name <- ["ash_onetime_facts", "Bad-Name"] do
      path = Path.join(temporary, "invalid_#{System.unique_integer([:positive])}")

      assert_raise Mix.Error, ~r/fact table name/i, fn ->
        File.mkdir_p!(path)
        Mix.Task.reenable("ash_onetime.gen.migrations")

        GenerateMigrations.run([
          "--repo",
          inspect(Repo),
          "--migrations-path",
          path,
          "--fact-tables",
          name
        ])
      end

      assert Path.wildcard(Path.join(path, "*_ash_onetime_context_boundary_facts.exs")) == []
    end
  end

  test "generates the existing-install logical partition upgrade", %{temporary: temporary} do
    Mix.Task.reenable("ash_onetime.gen.logical_partitions")

    path =
      LogicalPartitions.run([
        "--repo",
        inspect(Repo),
        "--migrations-path",
        temporary,
        "--timestamp",
        "20260820143000"
      ])

    assert Path.basename(path) == "20260820143000_add_ash_onetime_logical_partitions.exs"
    assert File.read!(path) == GenerateMigrations.render_logical_partition_upgrade(Repo, [])
  end

  test "Hex package unpack contains exactly all migration templates", %{temporary: temporary} do
    package = Path.join(temporary, "package")

    {output, status} =
      System.cmd("mix", ["hex.build", "--unpack", "--output", package],
        cd: File.cwd!(),
        stderr_to_stdout: true
      )

    assert status == 0, output

    templates =
      package
      |> Path.join("priv/templates/**/*")
      |> Path.wildcard()
      |> Enum.filter(&File.regular?/1)
      |> Enum.map(&Path.relative_to(&1, package))
      |> Enum.sort()

    assert templates == [
             "priv/templates/migrations/fact_tables.exs",
             "priv/templates/migrations/hash_partitioned.exs",
             "priv/templates/migrations/install.exs",
             "priv/templates/migrations/logical_partitions.exs",
             "priv/templates/migrations/rls_prune.exs",
             "priv/templates/migrations/roll_forward.exs"
           ]
  end

  defp run_generator(path, extra_arguments) do
    File.mkdir_p!(path)
    Mix.Task.reenable("ash_onetime.gen.migrations")

    GenerateMigrations.run(
      ["--repo", inspect(Repo), "--migrations-path", path] ++ extra_arguments
    )

    case Path.wildcard(Path.join(path, "*_ash_onetime_context_boundary_facts.exs")) do
      [facts] ->
        facts

      [] ->
        [generated] = Path.wildcard(Path.join(path, "*_install_ash_onetime.exs"))
        generated
    end
  end
end
